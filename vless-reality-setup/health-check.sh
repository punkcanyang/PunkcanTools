#!/bin/bash

#===============================================================================
# VLESS + Reality 健康检查脚本
# 检查 Xray 服务状态并在异常时自动重启
#===============================================================================

#-------------------------------------------------------------------------------
# 颜色定义
#-------------------------------------------------------------------------------
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
NC='\033[0m'

#-------------------------------------------------------------------------------
# 配置
#-------------------------------------------------------------------------------
LOG_FILE="/var/log/xray/health-check.log"
MAX_LOG_SIZE=10485760  # 10MB

#-------------------------------------------------------------------------------
# 日志函数
#-------------------------------------------------------------------------------
log() {
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    echo "[$timestamp] $1"
}

#-------------------------------------------------------------------------------
# 检查日志大小并轮转
#-------------------------------------------------------------------------------
rotate_log() {
    if [[ -f "$LOG_FILE" ]]; then
        local size=$(stat -f%z "$LOG_FILE" 2>/dev/null || stat -c%s "$LOG_FILE" 2>/dev/null)
        if [[ "$size" -gt "$MAX_LOG_SIZE" ]]; then
            mv "$LOG_FILE" "${LOG_FILE}.old"
            log "日志文件已轮转"
        fi
    fi
}

#-------------------------------------------------------------------------------
# 检查 Xray 服务状态
#-------------------------------------------------------------------------------
check_xray_service() {
    if systemctl is-active --quiet xray; then
        return 0
    else
        return 1
    fi
}

#-------------------------------------------------------------------------------
# 检查 Xray 端口是否监听
#-------------------------------------------------------------------------------
check_xray_port() {
    local port=$(jq -r '.inbounds[0].port' /usr/local/etc/xray/config.json 2>/dev/null)
    
    if [[ -z "$port" || "$port" == "null" ]]; then
        port=443
    fi
    
    if ss -tlnp | grep -q ":${port}"; then
        return 0
    else
        return 1
    fi
}

#-------------------------------------------------------------------------------
# 检查 Xray 进程
#-------------------------------------------------------------------------------
check_xray_process() {
    if pgrep -x "xray" > /dev/null; then
        return 0
    else
        return 1
    fi
}

#-------------------------------------------------------------------------------
# 重启 Xray 服务
#-------------------------------------------------------------------------------
restart_xray() {
    log "[WARN] 正在重启 Xray 服务..."
    systemctl restart xray
    sleep 3
    
    if check_xray_service; then
        log "[OK] Xray 服务重启成功"
        return 0
    else
        log "[ERROR] Xray 服务重启失败"
        return 1
    fi
}

#-------------------------------------------------------------------------------
# 发送告警 (可扩展)
#-------------------------------------------------------------------------------
send_alert() {
    local message="$1"
    log "[ALERT] $message"
    
    # 可以在这里添加邮件、Telegram、Webhook 等告警方式
    # 例如:
    # curl -s -X POST "https://api.telegram.org/bot<TOKEN>/sendMessage" \
    #     -d "chat_id=<CHAT_ID>&text=${message}"
}

#-------------------------------------------------------------------------------
# 主函数
#-------------------------------------------------------------------------------
main() {
    rotate_log
    
    log "开始健康检查..."
    
    local status=0
    
    # 检查服务状态
    if ! check_xray_service; then
        log "[ERROR] Xray 服务未运行"
        status=1
    else
        log "[OK] Xray 服务运行中"
    fi
    
    # 检查进程
    if ! check_xray_process; then
        log "[ERROR] Xray 进程不存在"
        status=1
    else
        log "[OK] Xray 进程存在"
    fi
    
    # 检查端口
    if ! check_xray_port; then
        log "[ERROR] Xray 端口未监听"
        status=1
    else
        log "[OK] Xray 端口监听正常"
    fi
    
    # 如果有问题，尝试重启
    if [[ $status -ne 0 ]]; then
        send_alert "Xray 服务异常，尝试重启"
        
        if ! restart_xray; then
            send_alert "Xray 服务重启失败，需要人工干预"
            exit 1
        fi
    fi
    
    log "健康检查完成"
    log "----------------------------------------"
}

# 执行主函数
main "$@"
