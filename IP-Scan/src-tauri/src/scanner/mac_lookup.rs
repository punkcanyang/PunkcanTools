/// Look up vendor by MAC address
pub fn lookup_vendor(mac: &str) -> String {
    // Normalize MAC address format (uppercase, colon-separated)
    let normalized = mac.to_uppercase().replace('-', ":").replace('.', ":");

    // Extract first 3 octets (OUI)
    let prefix = if normalized.len() >= 8 {
        &normalized[0..8]
    } else {
        return "Unknown".to_string();
    };

    MAC_VENDORS
        .get(prefix)
        .map(|v| v.to_string())
        .unwrap_or_else(|| "Unknown".to_string())
}

